const zhCache = new Map<string, string>()

/**
 * 生成图标的中文名（按 '-' 拆词根，逐个查表，未收录的保留英文）。
 * 例：`arrow-up-right` → "箭头上右"；`file-earmark-check` → "文件折角对勾"。
 */
export function zhLabel(name: string): string {
  const hit = zhCache.get(name)
  if (hit !== undefined) return hit
  const out = name
    .split('-')
    .map((p) => ZH[p] ?? p)
    .filter(Boolean)
    .join('')
  zhCache.set(name, out)
  return out
}

